// Get selected category
const urlParams = new URLSearchParams(window.location.search);
const category = urlParams.get("category") || "music";

const isDailyChallenge =
    urlParams.get("daily") === "1";

// Get questions
const questions = quizData[category] || quizData.music;


// Quiz variables
let currentQuestion = 0;
let score = 0;
let playerName = "";


// Page elements
const questionElement = document.getElementById("question");
const answersElement = document.getElementById("answers");
const resultElement = document.getElementById("result");

const registrationElement =
    document.getElementById("playerRegistration");

const quizAreaElement =
    document.getElementById("quizArea");

const playerNameInput =
    document.getElementById("playerName");

const startButton =
    document.getElementById("startButton");

const nameError =
    document.getElementById("nameError");

const playerWelcome =
    document.getElementById("playerWelcome");
const questionProgress =
    document.getElementById("questionProgress");



// Category names
const categoryNames = {
    music: "🎵 Music",
    movies: "🎬 Movies",
    sports: "⚽ Sports",
    art: "🎨 Art",
    history: "🌍 History"
};


// Display category
document.querySelector("header p").textContent =
    categoryNames[category] + " Quiz";


// Start quiz
startButton.addEventListener("click", startQuiz);


function startQuiz() {

    const enteredName =
        playerNameInput.value.trim();

    if (!enteredName) {

        nameError.textContent =
            "Please enter your name before starting.";

        return;
    }

    playerName = enteredName;
    if (typeof gtag === "function") {
    gtag("event", "quiz_started", {
        category: category
    });
}

    nameError.textContent = "";

    registrationElement.style.display = "none";
    quizAreaElement.style.display = "block";

    playerWelcome.textContent =
        "Good luck, " + playerName + "! 🌟";
    questions.sort(() => Math.random() - 0.5);

    currentQuestion = 0;
    score = 0;

    showQuestion();
}


// Show question
function showQuestion() {

    const current =
        questions[currentQuestion];

    questionElement.textContent =
        current.question;

    if (questionProgress) {
        questionProgress.textContent =
            `Question ${currentQuestion + 1} of ${questions.length}`;
    }
    answersElement.innerHTML = "";

    resultElement.innerHTML = "";

    current.answers.forEach(answer => {

        const button =
            document.createElement("button");

        button.textContent = answer;

        button.onclick = function () {

            checkAnswer(answer, button);

        };

        answersElement.appendChild(button);

    });

}


// Check answer
function checkAnswer(answer, clickedButton) {

    const correctAnswer =
        questions[currentQuestion].correct;

    const allButtons =
        answersElement.querySelectorAll("button");

    allButtons.forEach(button => {

        button.disabled = true;

    });


    if (answer === correctAnswer) {

        score++;

        clickedButton.textContent =
            "✅ " + clickedButton.textContent;

        resultElement.innerHTML =
            "<p>Correct! 🎉</p>";

    }

    else {

        clickedButton.textContent =
            "❌ " + clickedButton.textContent;

        resultElement.innerHTML =
            `<p>Not quite! The correct answer is <strong>${correctAnswer}</strong>.</p>`;

    }


    setTimeout(() => {

        currentQuestion++;

        if (currentQuestion < questions.length) {

            showQuestion();

        }

        else {

            showFinalResult();

        }

    }, 1200);

}
// Final result
function showFinalResult() {

    const percentage =
        Math.round(
            (score / questions.length) * 100
        );
    if (typeof gtag === "function") {
    gtag("event", "quiz_completed", {
        category: category,
        score: score,
        percentage: percentage
    });
}
    const isDailyChallenge =
    urlParams.get("daily") === "1";

if (isDailyChallenge && typeof gtag === "function") {
    gtag("event", "daily_challenge_completed", {
        category: category,
        score: score,
        percentage: percentage
    });
}

    // Save player's latest score locally
    const playerScore = {
        name: playerName,
        category: category,
        score: score,
        total: questions.length,
        percentage: percentage,
        dailyChallenge: isDailyChallenge,
        date: new Date().toISOString().split("T")[0]
    };

    localStorage.setItem(
        "famousFaceLatestScore",
        JSON.stringify(playerScore)
    );
    // Save quiz to permanent local history
let quizHistory = [];

try {
    quizHistory =
        JSON.parse(
            localStorage.getItem("famousFaceQuizHistory")
        ) || [];
} catch (error) {
    quizHistory = [];
}

quizHistory.push(playerScore);

localStorage.setItem(
    "famousFaceQuizHistory",
    JSON.stringify(quizHistory)
);

    // Save score to Supabase
    saveScoreToSupabase(playerScore);

    // Save Daily Challenge result locally
    if (isDailyChallenge) {

        const today =
            new Date().toISOString().split("T")[0];

        const dailyResult = {
            name: playerName,
            category: category,
            score: score,
            total: questions.length,
            percentage: percentage,
            date: today
        };

        localStorage.setItem(
            "famousFaceDailyScore",
            JSON.stringify(dailyResult)
        );
    }

    questionElement.textContent =
        isDailyChallenge
            ? "🔥 Daily Challenge Complete!"
            : "🏆 Quiz Complete!";

    answersElement.innerHTML = "";

    resultElement.innerHTML = `

        <h2>
            ${isDailyChallenge
                ? "🔥 Daily Challenge Complete!"
                : "Well done, " + playerName + "! 🎉"}
        </h2>

        <h3>
            ${isDailyChallenge
                ? "Today's Score"
                : "Your Score"}
        </h3>

        <p>
            ${score} out of ${questions.length}
        </p>

        <p>
            ${percentage}%
        </p>

        ${
            isDailyChallenge
                ? "<p>🏆 Your Daily Challenge result has been saved!</p>"
                : ""
        }

        <button onclick="shareScore()">
            📤 Share My Score
        </button>

        <br><br>

        <button onclick="restartQuiz()">
            🔄 Play Again
        </button>

        <br><br>

        <a href="index.html">
            🏠 Back to Home
        </a>

    `;
}



// Share score
async function shareScore() {
    if (typeof gtag === "function") {
    gtag("event", "score_shared", {
        category: category,
        score: score,
        total_questions: questions.length,
        percentage: Math.round(
            (score / questions.length) * 100
        )
    });
}

    const shareText =
        `🎉 I scored ${score}/${questions.length} (${Math.round(
            (score / questions.length) * 100
        )}%) on the FamousFace ${categoryNames[category]} Quiz! 🌟 Can you beat my score?`;

    const shareUrl =
        window.location.origin +
        window.location.pathname +
        window.location.search;

    if (navigator.share) {

        try {

            await navigator.share({
                title: "My FamousFace Score",
                text: shareText,
                url: shareUrl
            });

        } catch (error) {

            console.log("Share cancelled.");

        }

    } else {

        try {

            await navigator.clipboard.writeText(
                shareText + "\n" + shareUrl
            );

            alert(
                "🎉 Your score has been copied! You can now paste it anywhere."
            );

        } catch (error) {

            alert(
                "Please copy your score manually and share it with your friends!"
            );

        }
    }
}



// Restart quiz
function restartQuiz() {

    currentQuestion = 0;
    score = 0;

    quizAreaElement.style.display = "block";

    showQuestion();

}
async function saveScoreToSupabase(playerScore) {

    try {

        const response = await fetch(
            `${SUPABASE_URL}/rest/v1/scores`,
            {
                method: "POST",

                headers: {
                    "Content-Type": "application/json",
                    "apikey": SUPABASE_KEY,
                    "Authorization": `Bearer ${SUPABASE_KEY}`,
                    "Prefer": "return=minimal"
                },

                body: JSON.stringify({
                    player_name: playerScore.name,
                    category: playerScore.category,
                    score: playerScore.score,
                    total_questions: playerScore.total,
                    percentage: playerScore.percentage,
                    daily_challenge: playerScore.dailyChallenge || false
                })
            }
        );

        if (!response.ok) {

            const errorText =
                await response.text();

            console.error(
                "Supabase error:",
                errorText
            );

            return;
        }

        console.log(
            "Score successfully saved to Supabase!"
        );

    } catch (error) {

        console.error(
            "Could not save score:",
            error
        );

    }
}
