// Get selected category
const urlParams = new URLSearchParams(window.location.search);
const category = urlParams.get("category") || "music";


// Get questions
const questions = quizData[category] || quizData.music;


// Quiz variables
let currentQuestion = 0;
let score = 0;
let playerName = "";


// Page elements
const questionElement = document.getElementById("question");
const answersElement = document.getElementById("answers");
const resultElement = document.getElementById("result");

const registrationElement =
    document.getElementById("playerRegistration");

const quizAreaElement =
    document.getElementById("quizArea");

const playerNameInput =
    document.getElementById("playerName");

const startButton =
    document.getElementById("startButton");

const nameError =
    document.getElementById("nameError");

const playerWelcome =
    document.getElementById("playerWelcome");


// Category names
const categoryNames = {
    music: "🎵 Music",
    movies: "🎬 Movies",
    sports: "⚽ Sports",
    art: "🎨 Art",
    history: "🌍 History"
};


// Display category
document.querySelector("header p").textContent =
    categoryNames[category] + " Quiz";


// Start quiz
startButton.addEventListener("click", startQuiz);


function startQuiz() {

    const enteredName =
        playerNameInput.value.trim();

    if (!enteredName) {

        nameError.textContent =
            "Please enter your name before starting.";

        return;
    }

    playerName = enteredName;

    nameError.textContent = "";

    registrationElement.style.display = "none";
    quizAreaElement.style.display = "block";

    playerWelcome.textContent =
        "Good luck, " + playerName + "! 🌟";
    questions.sort(() => Math.random() - 0.5);

    currentQuestion = 0;
    score = 0;

    showQuestion();
}


// Show question
function showQuestion() {

    const current =
        questions[currentQuestion];

    questionElement.textContent =
        current.question;

    answersElement.innerHTML = "";

    resultElement.innerHTML = "";

    current.answers.forEach(answer => {

        const button =
            document.createElement("button");

        button.textContent = answer;

        button.onclick = function () {

            checkAnswer(answer, button);

        };

        answersElement.appendChild(button);

    });

}


// Check answer
function checkAnswer(answer, clickedButton) {

    const correctAnswer =
        questions[currentQuestion].correct;

    const allButtons =
        answersElement.querySelectorAll("button");

    allButtons.forEach(button => {

        button.disabled = true;

    });


    if (answer === correctAnswer) {

        score++;

        clickedButton.textContent =
            "✅ " + clickedButton.textContent;

        resultElement.innerHTML =
            "<p>Correct! 🎉</p>";

    }

    else {

        clickedButton.textContent =
            "❌ " + clickedButton.textContent;

        resultElement.innerHTML =
            `<p>Not quite! The correct answer is <strong>${correctAnswer}</strong>.</p>`;

    }


    setTimeout(() => {

        currentQuestion++;

        if (currentQuestion < questions.length) {

            showQuestion();

        }

        else {

            showFinalResult();

        }

    }, 1200);

}


// Final result
function showFinalResult() {

    const percentage =
        Math.round(
            (score / questions.length) * 100
        );


    // Save player's latest score locally
    const playerScore = {
        name: playerName,
        category: category,
        score: score,
        total: questions.length,
        percentage: percentage
    };

    localStorage.setItem(
        "famousFaceLatestScore",
        JSON.stringify(playerScore)
    );
    // Save score to Supabase
saveScoreToSupabase(playerScore);


    questionElement.textContent =
        "🏆 Quiz Complete!";


    answersElement.innerHTML = "";


    resultElement.innerHTML = `

        <h2>Well done, ${playerName}! 🎉</h2>

        <h3>Your Score</h3>

        <p>
            ${score} out of ${questions.length}
        </p>

        <p>
            ${percentage}%
        </p>

        <button onclick="restartQuiz()">
            🔄 Play Again
        </button>

        <br><br>

        <a href="index.html">
            🏠 Back to Home
        </a>

    `;

}


// Restart quiz
function restartQuiz() {

    currentQuestion = 0;
    score = 0;

    quizAreaElement.style.display = "block";

    showQuestion();

}
async function saveScoreToSupabase(playerScore) {

    try {

        const response = await fetch(
            `${SUPABASE_URL}/rest/v1/scores`,
            {
                method: "POST",

                headers: {
                    "Content-Type": "application/json",
                    "apikey": SUPABASE_KEY,
                    "Authorization": `Bearer ${SUPABASE_KEY}`,
                    "Prefer": "return=minimal"
                },

                body: JSON.stringify({
                    player_name: playerScore.name,
                    category: playerScore.category,
                    score: playerScore.score,
                    total_questions: playerScore.total,
                    percentage: playerScore.percentage
                })
            }
        );


        if (!response.ok) {

            const errorText =
                await response.text();

            console.error(
                "Supabase error:",
                errorText
            );

            return;
        }


        console.log(
            "Score successfully saved to Supabase!"
        );

    } catch (error) {

        console.error(
            "Could not save score:",
            error
        );

    }
}
